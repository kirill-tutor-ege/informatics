# Алгоритм вычисления значения функции F(n) и G(n), где n – целое число, задан следующими соотношениями:
# F(n) = 2 × (G(n − 3) + 8);
# G(n) = 2 × n, если n < 10.
# G(n) = G(n − 2) + 1, если n ≥ 10.
# Чему равно значение выражения F(15548)?
from functools import *

@lru_cache(None)
def F(n):
    return 2 * (G(n - 3) + 8)

@lru_cache(None)
def G(n):
    if n < 10:
        return 2 * n
    if n >= 10:
        return G(n - 2) + 1

for i in range(10, 15548 + 1):
    F(i)

print(F(15548))
